//! Enforceable engagement envelope.
//!
//! Scope in most proxies is a hint the tool itself ignores. Here the envelope is
//! the single place that decides whether a request may leave the process, and every
//! decision is written to a hash-chained audit log.
//!
//! Three modes, chosen by configuration:
//!
//! - **Unrestricted** — no envelope was asked for. Everything is allowed and
//!   nothing is audited. This is the default so the tool still works out of the box,
//!   and the UI says so in as many words rather than implying a guarantee.
//! - **Enforced** — an envelope loaded and validated. Every request is checked
//!   against window, scope, method and budget, and audited.
//! - **Broken** — an envelope was requested but could not be loaded. All traffic is
//!   denied. Failing closed is the only defensible behaviour: the operator asked for
//!   a guarantee, and silently running without one is how incidents happen.
//!
//! Rate limiting (`max_rps`) is expressed as a minimum delay for *generated*
//! traffic — Intruder payloads, active checks, Repeater — and deliberately does not
//! apply to proxied browser traffic, where delaying requests would break the human
//! workflow without reducing risk.

pub mod audit;
pub mod envelope;

use std::{
    env,
    path::{Path, PathBuf},
    sync::Mutex,
    time::Duration,
};

use chrono::Utc;
use tracing::warn;

pub use audit::{AuditLog, AuditRecord};
pub use envelope::{CompiledEnvelope, MethodVerdict, ScopeVerdict};

/// Where the envelope is read from when `PROXIMA_ENGAGEMENT` is not set.
pub const DEFAULT_ENGAGEMENT_PATH: &str = ".proxima/engagement.yaml";
const ENGAGEMENT_ENV: &str = "PROXIMA_ENGAGEMENT";

/// Whether a request was observed through the proxy or generated by a tool tab.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Traffic {
    Proxied,
    Generated,
}

impl Traffic {
    pub fn label(self) -> &'static str {
        match self {
            Self::Proxied => "proxied",
            Self::Generated => "generated",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DenyReason {
    /// The envelope was requested but could not be loaded; fail closed.
    EnvelopeUnavailable(String),
    /// A halt condition tripped; a human must resume.
    Halted(String),
    OutsideWindow { from: Option<String>, to: Option<String> },
    MethodDenied(String),
    MethodNotInAllowList(String),
    Excluded,
    OutOfScope,
    BudgetExhausted(u64),
}

impl std::fmt::Display for DenyReason {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::EnvelopeUnavailable(error) => {
                write!(formatter, "engagement envelope unavailable: {error}")
            }
            Self::Halted(reason) => write!(formatter, "engagement halted: {reason}"),
            Self::OutsideWindow { from, to } => write!(
                formatter,
                "outside the authorized window{}",
                match (from, to) {
                    (Some(from), Some(to)) => format!(" ({from} → {to})"),
                    (Some(from), None) => format!(" (starts {from})"),
                    (None, Some(to)) => format!(" (ends {to})"),
                    (None, None) => String::new(),
                }
            ),
            Self::MethodDenied(method) => {
                write!(formatter, "method {method} is denied by the engagement envelope")
            }
            Self::MethodNotInAllowList(method) => write!(
                formatter,
                "method {method} is not in the envelope's allowed method list"
            ),
            Self::Excluded => write!(formatter, "URL matches an excluded pattern"),
            Self::OutOfScope => write!(formatter, "URL is outside the engagement scope"),
            Self::BudgetExhausted(limit) => {
                write!(formatter, "request budget of {limit} requests is exhausted")
            }
        }
    }
}

impl DenyReason {
    /// Short tag for audit entries and status lines.
    pub fn code(&self) -> &'static str {
        match self {
            Self::EnvelopeUnavailable(_) => "envelope_unavailable",
            Self::Halted(_) => "halted",
            Self::OutsideWindow { .. } => "outside_window",
            Self::MethodDenied(_) => "method_denied",
            Self::MethodNotInAllowList(_) => "method_not_allowed",
            Self::Excluded => "excluded",
            Self::OutOfScope => "out_of_scope",
            Self::BudgetExhausted(_) => "budget_exhausted",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Decision {
    Allow,
    Deny(DenyReason),
}

impl Decision {
    pub fn is_allowed(&self) -> bool {
        matches!(self, Self::Allow)
    }

    pub fn reason(&self) -> Option<&DenyReason> {
        match self {
            Self::Allow => None,
            Self::Deny(reason) => Some(reason),
        }
    }
}

#[derive(Debug)]
enum Mode {
    Unrestricted,
    Enforced,
    Broken(String),
}

#[derive(Debug, Default)]
struct Budget {
    requests: u64,
    denials: u64,
    observed: u64,
    count_429: u32,
    count_5xx: u64,
    halted: Option<String>,
}

#[derive(Debug)]
pub struct Policy {
    mode: Mode,
    envelope: Option<CompiledEnvelope>,
    audit: Option<AuditLog>,
    state: Mutex<Budget>,
    note: String,
    source: Option<PathBuf>,
}

impl Policy {
    /// Load the envelope named by `PROXIMA_ENGAGEMENT`, or `.proxima/engagement.yaml`
    /// when present. Never fails: problems become a [`Mode::Broken`] policy that
    /// denies everything and says why.
    pub fn load_default() -> Self {
        let explicit = env::var_os(ENGAGEMENT_ENV).map(PathBuf::from);
        let path = explicit
            .clone()
            .unwrap_or_else(|| PathBuf::from(DEFAULT_ENGAGEMENT_PATH));

        if explicit.is_none() && !path.exists() {
            return Self::unrestricted(format!(
                "no engagement envelope at {DEFAULT_ENGAGEMENT_PATH}: scope is NOT enforced"
            ));
        }

        match Self::load(&path) {
            Ok(policy) => policy,
            Err(error) => {
                warn!(
                    path = %path.display(),
                    %error,
                    "engagement envelope rejected; denying all traffic"
                );
                Self::broken(format!("{}: {error}", path.display()))
            }
        }
    }

    pub fn load(path: impl AsRef<Path>) -> Result<Self, String> {
        let path = path.as_ref();
        let envelope = CompiledEnvelope::from_path(path)?;
        let audit = if envelope.envelope.audit.is_enabled() {
            let log_path = envelope.envelope.audit.log_path();
            Some(AuditLog::open(&log_path)?)
        } else {
            None
        };
        let note = envelope.summary();
        Ok(Self::enforced(envelope, audit, note, Some(path.to_path_buf())))
    }

    /// No envelope was requested. Allow everything, audit nothing, and say so.
    pub fn unrestricted(note: impl Into<String>) -> Self {
        Self {
            mode: Mode::Unrestricted,
            envelope: None,
            audit: None,
            state: Mutex::new(Budget::default()),
            note: note.into(),
            source: None,
        }
    }

    /// An envelope was requested but is unusable. Deny everything.
    pub fn broken(error: impl Into<String>) -> Self {
        let error = error.into();
        Self {
            mode: Mode::Broken(error.clone()),
            envelope: None,
            audit: None,
            state: Mutex::new(Budget::default()),
            note: format!("envelope rejected: {error}"),
            source: None,
        }
    }

    fn enforced(
        envelope: CompiledEnvelope,
        audit: Option<AuditLog>,
        note: String,
        source: Option<PathBuf>,
    ) -> Self {
        Self {
            mode: Mode::Enforced,
            envelope: Some(envelope),
            audit,
            state: Mutex::new(Budget::default()),
            note,
            source,
        }
    }

    /// The one gate every outbound request must pass.
    pub fn authorize(&self, traffic: Traffic, method: &str, uri: &str) -> Decision {
        match &self.mode {
            Mode::Unrestricted => Decision::Allow,
            Mode::Broken(error) => {
                let reason = DenyReason::EnvelopeUnavailable(error.clone());
                self.audit(traffic, method, uri, Some(&reason));
                Decision::Deny(reason)
            }
            Mode::Enforced => {
                let Some(envelope) = &self.envelope else {
                    return Decision::Allow;
                };
                let mut state = self.lock_state();
                let decision = evaluate(envelope, &mut state, method, uri);
                match &decision {
                    Decision::Allow => {
                        state.requests += 1;
                        drop(state);
                        self.audit(traffic, method, uri, None);
                    }
                    Decision::Deny(reason) => {
                        state.denials += 1;
                        drop(state);
                        self.audit(traffic, method, uri, Some(reason));
                    }
                }
                decision
            }
        }
    }

    /// Feed a response back into the halt conditions.
    pub fn observe(&self, status: u16) {
        let Some(envelope) = &self.envelope else {
            return;
        };
        let Some(halt) = &envelope.envelope.limits.halt_on else {
            return;
        };

        let tripped = {
            let mut state = self.lock_state();
            state.observed += 1;
            if status == 429 {
                state.count_429 = state.count_429.saturating_add(1);
            }
            if (500..=599).contains(&status) {
                state.count_5xx += 1;
            }

            let mut reason: Option<String> = None;
            if state.halted.is_none() {
                if let Some(limit) = halt.status_429 {
                    if state.count_429 >= limit {
                        reason = Some(format!("{} response(s) with status 429", state.count_429));
                    }
                }
                if reason.is_none() {
                    if let Some(rate_limit) = halt.status_5xx_rate {
                        let minimum = halt.min_samples.unwrap_or(20);
                        if state.observed >= minimum {
                            let rate = state.count_5xx as f64 / state.observed as f64;
                            if rate > rate_limit {
                                reason =
                                    Some(format!("{:.0}% of responses were 5xx", rate * 100.0));
                            }
                        }
                    }
                }
            }
            reason
        };

        if let Some(reason) = tripped {
            {
                let mut state = self.lock_state();
                state.halted = Some(reason.clone());
            }
            warn!(%reason, "engagement halt condition tripped; denying further traffic");
            if let Some(audit) = &self.audit {
                audit.record(
                    AuditRecord {
                        action: "halt",
                        traffic: "system",
                        method: "-",
                        uri: "-",
                        reason: Some(reason.as_str()),
                        envelope_id: self.envelope_id(),
                    },
                );
            }
        }
    }

    /// Minimum spacing between generated requests, from `limits.max_rps`.
    pub fn min_delay(&self) -> Option<Duration> {
        self.envelope.as_ref().and_then(CompiledEnvelope::min_delay)
    }

    pub fn is_enforced(&self) -> bool {
        matches!(self.mode, Mode::Enforced)
    }

    pub fn is_broken(&self) -> bool {
        matches!(self.mode, Mode::Broken(_))
    }

    pub fn envelope_id(&self) -> Option<&str> {
        self.envelope.as_ref().map(CompiledEnvelope::id)
    }

    pub fn source(&self) -> Option<&Path> {
        self.source.as_deref()
    }

    /// One line for the UI: what is enforced, or why nothing is.
    pub fn status_line(&self) -> String {
        match &self.mode {
            Mode::Enforced => self.note.clone(),
            Mode::Unrestricted => self.note.clone(),
            Mode::Broken(error) => format!("ENGAGEMENT BROKEN — denying all traffic: {error}"),
        }
    }

    pub fn requests_used(&self) -> u64 {
        self.lock_state().requests
    }

    pub fn denials(&self) -> u64 {
        self.lock_state().denials
    }

    pub fn halted(&self) -> Option<String> {
        self.lock_state().halted.clone()
    }

    pub fn audit_entries(&self) -> u64 {
        self.audit.as_ref().map(AuditLog::entries).unwrap_or(0)
    }

    pub fn audit_failures(&self) -> u64 {
        self.audit.as_ref().map(AuditLog::failures).unwrap_or(0)
    }

    pub fn flush_audit(&self) {
        if let Some(audit) = &self.audit {
            audit.flush();
        }
    }

    fn lock_state(&self) -> std::sync::MutexGuard<'_, Budget> {
        match self.state.lock() {
            Ok(guard) => guard,
            Err(poisoned) => poisoned.into_inner(),
        }
    }

    fn audit(&self, traffic: Traffic, method: &str, uri: &str, reason: Option<&DenyReason>) {
        let Some(audit) = &self.audit else {
            return;
        };
        let envelope_id = self.envelope_id();
        match reason {
            None => audit.record(
                AuditRecord::allow(traffic.label(), method, uri).with_envelope(envelope_id),
            ),
            Some(reason) => {
                let text = reason.to_string();
                audit.record(
                    AuditRecord::deny(traffic.label(), method, uri, &text)
                        .with_envelope(envelope_id),
                );
            }
        }
    }
}

fn evaluate(
    envelope: &CompiledEnvelope,
    state: &mut Budget,
    method: &str,
    uri: &str,
) -> Decision {
    if let Some(reason) = &state.halted {
        return Decision::Deny(DenyReason::Halted(reason.clone()));
    }

    if let Some(window) = &envelope.envelope.limits.window {
        let now = Utc::now();
        let before = window.from.map(|from| now < from).unwrap_or(false);
        let after = window.to.map(|to| now >= to).unwrap_or(false);
        if before || after {
            return Decision::Deny(DenyReason::OutsideWindow {
                from: window.from.map(|from| from.to_rfc3339()),
                to: window.to.map(|to| to.to_rfc3339()),
            });
        }
    }

    match envelope.method_allowed(method) {
        MethodVerdict::Allowed => {}
        MethodVerdict::Denied => {
            return Decision::Deny(DenyReason::MethodDenied(method.to_ascii_uppercase()))
        }
        MethodVerdict::NotInAllowList => {
            return Decision::Deny(DenyReason::MethodNotInAllowList(method.to_ascii_uppercase()))
        }
    }

    match envelope.scope_of(uri) {
        ScopeVerdict::Included => {}
        ScopeVerdict::Excluded => return Decision::Deny(DenyReason::Excluded),
        ScopeVerdict::OutOfScope => return Decision::Deny(DenyReason::OutOfScope),
    }

    if let Some(limit) = envelope.envelope.limits.max_requests_total {
        if state.requests >= limit {
            return Decision::Deny(DenyReason::BudgetExhausted(limit));
        }
    }

    Decision::Allow
}

#[cfg(test)]
mod tests {
    use super::*;

    const BASE: &str = r#"
apiVersion: proxima.dev/v1alpha1
kind: Engagement
metadata:
  id: acme-staging
scope:
  include: ['^https://staging\.example\.test(/|$)']
"#;

    fn enforced(source: &str) -> Policy {
        let envelope = CompiledEnvelope::parse(source).expect("valid envelope");
        Policy::enforced(envelope, None, "test".to_string(), None)
    }

    #[test]
    fn in_scope_traffic_is_allowed() {
        let policy = enforced(BASE);
        assert_eq!(
            policy.authorize(Traffic::Proxied, "GET", "https://staging.example.test/api"),
            Decision::Allow
        );
        assert_eq!(policy.requests_used(), 1);
    }

    #[test]
    fn out_of_scope_traffic_is_denied() {
        let policy = enforced(BASE);
        let decision = policy.authorize(Traffic::Proxied, "GET", "https://prod.example.test/api");
        assert_eq!(decision, Decision::Deny(DenyReason::OutOfScope));
        assert_eq!(policy.denials(), 1);
        // A denial must not consume the request budget.
        assert_eq!(policy.requests_used(), 0);
    }

    #[test]
    fn excluded_paths_are_denied_even_when_in_scope() {
        let policy = enforced(&format!("{BASE}  exclude: ['/admin']\n"));
        assert_eq!(
            policy.authorize(Traffic::Proxied, "GET", "https://staging.example.test/admin/x"),
            Decision::Deny(DenyReason::Excluded)
        );
    }

    #[test]
    fn denied_methods_are_denied() {
        let policy = enforced(&format!("{BASE}\nlimits:\n  deny_methods: [DELETE]\n"));
        assert_eq!(
            policy.authorize(Traffic::Proxied, "DELETE", "https://staging.example.test/api"),
            Decision::Deny(DenyReason::MethodDenied("DELETE".to_string()))
        );
    }

    #[test]
    fn budget_exhaustion_denies_further_requests() {
        let policy = enforced(&format!("{BASE}\nlimits:\n  max_requests_total: 2\n"));
        let uri = "https://staging.example.test/api";
        assert_eq!(policy.authorize(Traffic::Proxied, "GET", uri), Decision::Allow);
        assert_eq!(policy.authorize(Traffic::Proxied, "GET", uri), Decision::Allow);
        assert_eq!(
            policy.authorize(Traffic::Proxied, "GET", uri),
            Decision::Deny(DenyReason::BudgetExhausted(2))
        );
    }

    #[test]
    fn expired_window_denies_everything() {
        let policy = enforced(&format!(
            "{BASE}\nlimits:\n  window:\n    from: 2020-01-01T00:00:00Z\n    to: 2020-01-02T00:00:00Z\n"
        ));
        let decision = policy.authorize(Traffic::Proxied, "GET", "https://staging.example.test/");
        assert!(matches!(decision, Decision::Deny(DenyReason::OutsideWindow { .. })));
    }

    #[test]
    fn future_window_denies_everything() {
        let policy = enforced(&format!(
            "{BASE}\nlimits:\n  window:\n    from: 2099-01-01T00:00:00Z\n"
        ));
        assert!(!policy
            .authorize(Traffic::Proxied, "GET", "https://staging.example.test/")
            .is_allowed());
    }

    #[test]
    fn halt_on_429_stops_further_traffic() {
        let policy = enforced(&format!("{BASE}\nlimits:\n  halt_on:\n    status_429: 2\n"));
        let uri = "https://staging.example.test/api";
        policy.observe(200);
        policy.observe(429);
        assert!(policy.halted().is_none());
        policy.observe(429);
        assert!(policy.halted().is_some());
        assert!(matches!(
            policy.authorize(Traffic::Proxied, "GET", uri),
            Decision::Deny(DenyReason::Halted(_))
        ));
    }

    #[test]
    fn halt_on_5xx_rate_respects_min_samples() {
        let policy = enforced(&format!(
            "{BASE}\nlimits:\n  halt_on:\n    status_5xx_rate: 0.5\n    min_samples: 4\n"
        ));
        for _ in 0..3 {
            policy.observe(500);
        }
        assert!(policy.halted().is_none(), "must not trip before min_samples");
        policy.observe(500);
        assert!(policy.halted().is_some());
    }

    #[test]
    fn unrestricted_policy_allows_everything() {
        let policy = Policy::unrestricted("no envelope");
        assert_eq!(
            policy.authorize(Traffic::Proxied, "DELETE", "https://anything.test/x"),
            Decision::Allow
        );
        assert!(!policy.is_enforced());
        assert!(policy.audit_entries() == 0);
    }

    #[test]
    fn broken_policy_denies_everything() {
        let policy = Policy::broken("bad yaml");
        assert!(policy.is_broken());
        let decision = policy.authorize(Traffic::Proxied, "GET", "https://staging.example.test/");
        assert!(matches!(decision, Decision::Deny(DenyReason::EnvelopeUnavailable(_))));
    }

    #[test]
    fn generated_traffic_is_checked_like_proxied_traffic() {
        let policy = enforced(BASE);
        assert_eq!(
            policy.authorize(Traffic::Generated, "GET", "https://staging.example.test/api"),
            Decision::Allow
        );
        assert!(!policy
            .authorize(Traffic::Generated, "GET", "https://elsewhere.test/")
            .is_allowed());
    }

    /// The gate and the log have to be one object: a decision that is enforced but
    /// not recorded is unprovable after the fact.
    #[test]
    fn decisions_are_written_to_the_audit_chain() {
        let path = std::env::temp_dir().join(format!(
            "proxima-policy-audit-{}-{}.log",
            std::process::id(),
            Utc::now().timestamp_nanos_opt().unwrap_or_default()
        ));
        let _ = std::fs::remove_file(&path);

        let envelope = CompiledEnvelope::parse(BASE).expect("valid envelope");
        let log = AuditLog::open(&path).expect("audit log opens");
        let policy = Policy::enforced(envelope, Some(log), "test".to_string(), None);

        policy.authorize(Traffic::Proxied, "GET", "https://staging.example.test/api");
        policy.authorize(Traffic::Proxied, "GET", "https://prod.example.test/api");
        policy.flush_audit();

        assert_eq!(policy.audit_entries(), 2);
        assert_eq!(audit::verify(&path).expect("chain verifies"), 2);
        let _ = std::fs::remove_file(&path);
    }

    #[test]
    fn min_delay_comes_from_the_envelope() {
        let policy = enforced(&format!("{BASE}\nlimits:\n  max_rps: 10\n"));
        assert_eq!(policy.min_delay(), Some(Duration::from_millis(100)));
    }

    #[test]
    fn deny_reasons_read_like_sentences() {
        let reason = DenyReason::OutOfScope;
        assert_eq!(reason.to_string(), "URL is outside the engagement scope");
        assert_eq!(reason.code(), "out_of_scope");
    }
}
